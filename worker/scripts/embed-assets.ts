/**
 * Embed frontend build artifacts into the Worker.
 * Run AFTER `npm run build` in frontend/.
 * Generates src/frontend-assets.ts with inline content strings.
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(__dirname, '../../frontend/dist');
const outFile = resolve(__dirname, '../src/frontend-assets.ts');

// Read built files
const indexHtml = readFileSync(resolve(distDir, 'index.html'), 'utf-8');

// Find the JS asset in assets/ directory
const assets = readdirSync(resolve(distDir, 'assets'));
let mainJs = '';
let mainJsName = '';
for (const f of assets) {
  if (f.endsWith('.js')) {
    mainJs = readFileSync(resolve(distDir, 'assets', f), 'utf-8');
    mainJsName = f;
    break;
  }
}

// Inline CSS: read every .css in assets/ (sorted, deterministic) and replace
// the <link rel="stylesheet" href="/assets/*.css"> tag(s) in index.html with
// <style>…</style>. The /assets/* route in index.ts only serves .js, so a
// linked stylesheet would fall back to HTML and the admin UI would ship
// unstyled; inlining keeps the worker self-contained with no route change.
// External stylesheets (e.g. Google Fonts) are untouched — only /assets/*.css.
const cssFiles = assets.filter((f) => f.endsWith('.css')).sort();
let css = '';
for (const f of cssFiles) {
  css += readFileSync(resolve(distDir, 'assets', f), 'utf-8') + '\n';
}
if (cssFiles.length === 0) {
  throw new Error('No .css asset found in frontend/dist/assets — did the frontend build emit CSS?');
}
if (css.includes('</style')) {
  throw new Error('CSS contains "</style" and cannot be inlined safely');
}
const cssLinkPattern = /<link[^>]*href="\/assets\/[^"]*\.css"[^>]*>/g;
const inlinedHtml = indexHtml.replace(cssLinkPattern, () => `<style>\n${css}</style>`);
if (/<link[^>]*href="\/assets\/[^"]*\.css"/.test(inlinedHtml)) {
  throw new Error('A /assets/*.css <link> remains in index.html after inlining');
}

const content = `// Auto-generated by embed-assets.ts — do not edit manually
// Generated from frontend/dist/ build output

export const FRONTEND_HTML = ${JSON.stringify(inlinedHtml)};

export const FRONTEND_JS_NAME = ${JSON.stringify(mainJsName)};

export const FRONTEND_JS_CONTENT = ${JSON.stringify(mainJs)};
`;

writeFileSync(outFile, content, 'utf-8');
console.log(`✅ Generated ${outFile}`);
console.log(`   HTML: ${inlinedHtml.length} bytes`);
console.log(`   CSS:  ${cssFiles.join(', ')} (${css.length} bytes, inlined)`);
console.log(`   JS:   ${mainJsName} (${mainJs.length} bytes)`);
